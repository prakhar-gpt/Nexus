"""LangGraph execution nodes: model decision, tool execution, deterministic checking, and routing."""

from __future__ import annotations

import time
from langchain_core.messages import AIMessage, HumanMessage, SystemMessage, ToolMessage
from langgraph.config import get_stream_writer

from agent.nexus.checker import check_answer, is_clarification
from agent.nexus.state import AgentState, MAX_TOOL_STEPS, MESSAGE_TAIL, STEP_LIMIT, format_status_line
from agent.nexus.tools import (
    TOOLS,
    execute_kb,
    execute_python,
    execute_query,
    execute_schema,
    parse_tool_args,
)


def extract_visible_text(message) -> str:
    """Extract user-facing text from message, filtering out internal reasoning blocks."""
    content = getattr(message, "content", "")
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for part in content:
            if isinstance(part, str):
                parts.append(part)
                continue
            if not isinstance(part, dict):
                continue
            kind = str(part.get("type") or "")
            if kind in {"reasoning", "thinking", "reasoning_content"}:
                continue
            parts.append(str(part.get("text") or ""))
        return "".join(parts)
    return str(content or "")


def clean_answer_text(message) -> str:
    """Return stripped visible text for an answer message."""
    return extract_visible_text(message).strip()


def chunk_text(message) -> str:
    """Return token delta text for streaming chunks, ignoring tool calls and non-assistant content."""
    kind = getattr(message, "type", "")
    if kind in {"tool", "human", "system"}:
        return ""
    if getattr(message, "tool_call_chunks", None):
        return ""
    return extract_visible_text(message)


def _emit(payload: dict) -> None:
    try:
        get_stream_writer()(payload)
    except Exception:
        return


def agent_node(state: AgentState, model, system_prompt: str) -> dict:
    """Invoke the chat model to either generate an answer or pick a tool."""
    allowed = state.get("step_count", 0) < MAX_TOOL_STEPS
    chat = model.bind_tools(TOOLS) if allowed else model
    tail = list(state.get("messages") or [])[-MESSAGE_TAIL:]
    try:
        response = chat.invoke([SystemMessage(content=system_prompt), *tail])
    except Exception:
        response = AIMessage(content="The model could not be reached.")
    return {"messages": [response]}


def route_next_step(state: AgentState) -> str:
    """Route to 'tools' if the agent requested tool calls within step budget, else 'checker'."""
    last = (state.get("messages") or [None])[-1]
    calls = getattr(last, "tool_calls", None)
    if calls and state.get("step_count", 0) < MAX_TOOL_STEPS:
        return "tools"
    return "checker"


def tools_node(state: AgentState) -> dict:
    """Execute tool calls generated by the agent, stream progress, and return observations."""
    last = state["messages"][-1]
    workspace_id = int(state["workspace_id"])
    allowed_dataset_ids = state.get("allowed_dataset_ids")
    rows = list(state.get("rows") or [])
    sqls = list(state.get("sqls") or [])
    steps = list(state.get("steps") or [])
    python_rows = list(state.get("python_rows") or [])
    tools_used = list(state.get("tools_used") or [])
    sql_results = dict(state.get("sql_results") or {})
    messages = []

    for call in last.tool_calls:
        name = call.get("name") or ""
        call_id = str(call.get("id") or f"{name}-{len(steps)}")
        args = parse_tool_args(call)

        _emit(
            {
                "id": call_id,
                "tool": name or "unknown",
                "status": "running",
                "detail": format_status_line(name, "running"),
            }
        )

        started = time.perf_counter()
        query = None
        found: list[dict] = []

        if name == "get_schema":
            tools_used.append("get_schema")
            text = execute_schema(workspace_id, allowed_dataset_ids=allowed_dataset_ids)
        elif name == "run_sql":
            tools_used.append("run_sql")
            text, found, query = execute_query(str(args.get("sql") or ""), workspace_id, allowed_dataset_ids=allowed_dataset_ids)
            rows.extend(found)
            if query:
                sqls.append(query)
                sql_idx = len(sqls)
                sql_results[f"sql_{sql_idx}"] = found
                sql_results[call_id] = found
        elif name == "read_kb":
            tools_used.append("read_kb")
            text = execute_kb(str(args.get("path") or ""))
        elif name == "run_python":
            tools_used.append("run_python")
            code = str(args.get("code") or "")
            inputs = list(args.get("inputs") or [])
            text, py_results = execute_python(code, inputs, rows, sql_results)
            for label, value in py_results.items():
                python_rows.append({"label": label, "value": value})
        else:
            text = "rejected: unknown tool"

        elapsed = int((time.perf_counter() - started) * 1000)
        status = "error" if text.startswith("rejected") else "ok"

        _emit(
            {
                "id": call_id,
                "tool": name or "unknown",
                "status": status,
                "ms": elapsed,
                "detail": format_status_line(name, status),
                "query": query,
                "row_count": len(found),
                "input": args,
                "output": text,
            }
        )

        steps.append(
            {
                "id": call_id,
                "tool": name or "unknown",
                "status": status,
                "ms": elapsed,
                "detail": format_status_line(name, status),
                "query": query,
                "input": args,
                "output": text,
            }
        )
        messages.append(ToolMessage(content=text, tool_call_id=call_id))

    return {
        "messages": messages,
        "rows": rows,
        "sqls": sqls,
        "steps": steps,
        "python_rows": python_rows,
        "tools_used": tools_used,
        "sql_results": sql_results,
        "step_count": state.get("step_count", 0) + len(last.tool_calls),
    }


def checker_node(state: AgentState) -> dict:
    """Audit the drafted answer against SQL results, Python results, and question context."""
    last = (state.get("messages") or [None])[-1]
    if getattr(last, "tool_calls", None):
        answer = STEP_LIMIT
    else:
        answer = clean_answer_text(last) or "No answer was produced."

    rows = list(state.get("rows") or [])
    sqls = list(state.get("sqls") or [])
    python_rows = list(state.get("python_rows") or [])
    lowered = answer.lower()

    if sqls or python_rows:
        kind = "sql"
    elif "cannot answer" in lowered or "refus" in lowered:
        kind = "refusal"
    elif is_clarification(answer):
        kind = "clarification"
    else:
        kind = "unknown"

    question_text = None
    for msg in reversed(state.get("messages") or []):
        if isinstance(msg, HumanMessage) or getattr(msg, "type", "") == "human":
            question_text = str(getattr(msg, "content", ""))
            break

    py_dict = {
        item.get("label", str(i)): item.get("value")
        for i, item in enumerate(python_rows)
        if isinstance(item, dict)
    }

    check = check_answer(
        answer,
        rows,
        python_results=py_dict,
        question_text=question_text,
    )

    if kind in ("refusal", "clarification"):
        check = {"status": "verified", "verified": True, "untraced": [], "matched": []}

    steps = list(state.get("steps") or [])
    detail = "numbers match the tool output" if check.get("verified") else "untraced number"
    if kind == "clarification":
        detail = "clarification requested"
    elif kind == "refusal":
        detail = "question refused"

    steps.append(
        {
            "tool": "checker",
            "status": "ok" if check.get("verified") else "caveat",
            "ms": 0,
            "detail": detail,
        }
    )
    return {"answer": answer, "check": check, "kind": kind, "steps": steps}
