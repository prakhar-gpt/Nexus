"""Tools execution node dispatching tool calls and streaming progress."""

from __future__ import annotations

import time
from langchain_core.messages import ToolMessage
from langgraph.config import get_stream_writer

from packages.agent.state import AgentState, format_status_line
from packages.agent.tools.handlers import (
    execute_kb,
    execute_query,
    execute_schema,
    parse_tool_args,
)


def _emit(payload: dict) -> None:
    try:
        get_stream_writer()(payload)
    except Exception:
        return


def tools_node(state: AgentState) -> dict:
    """Execute tool calls generated by the agent, stream progress, and return observations."""
    last = state["messages"][-1]
    workspace_id = int(state["workspace_id"])
    rows = list(state.get("rows") or [])
    sqls = list(state.get("sqls") or [])
    steps = list(state.get("steps") or [])
    messages = []

    for call in last.tool_calls:
        name = call.get("name") or ""
        call_id = str(call.get("id") or f"{name}-{len(steps)}")
        args = parse_tool_args(call)

        _emit(
            {
                "id": call_id,
                "tool": name or "unknown",
                "status": "running",
                "detail": format_status_line(name, "running"),
            }
        )

        started = time.perf_counter()
        query = None
        found: list[dict] = []

        if name == "get_schema":
            text = execute_schema(workspace_id)
        elif name == "run_sql":
            text, found, query = execute_query(str(args.get("sql") or ""), workspace_id)
            rows.extend(found)
            if query:
                sqls.append(query)
        elif name == "read_kb":
            text = execute_kb(str(args.get("path") or ""))
        else:
            text = "rejected: unknown tool"

        elapsed = int((time.perf_counter() - started) * 1000)
        status = "error" if text.startswith("rejected") else "ok"

        _emit(
            {
                "id": call_id,
                "tool": name or "unknown",
                "status": status,
                "ms": elapsed,
                "detail": format_status_line(name, status),
                "query": query,
                "row_count": len(found),
            }
        )

        steps.append(
            {
                "id": call_id,
                "tool": name or "unknown",
                "status": status,
                "ms": elapsed,
                "detail": format_status_line(name, status),
            }
        )

        messages.append(
            ToolMessage(content=text, tool_call_id=call.get("id") or "missing")
        )

    return {
        "messages": messages,
        "rows": rows,
        "sqls": sqls,
        "steps": steps,
        "step_count": state.get("step_count", 0) + 1,
    }
